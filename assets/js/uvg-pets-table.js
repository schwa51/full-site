export const UVG_PET_ROLL_GROUPS = {
  mien: {
    label: "Mien",
    columns: ["mien"],
  },
  form: {
    label: "Morph, attack, and ability",
    columns: ["morph", "attack", "ability"],
  },
  likes: {
    label: "Likes",
    columns: ["likes"],
  },
};

export function petResultFor(group, roll) {
  const definition = UVG_PET_ROLL_GROUPS[group];
  if (!definition || !Number.isInteger(roll) || roll < 1 || roll > UVG_PETS_TABLE.length) {
    return null;
  }

  const row = UVG_PETS_TABLE[roll - 1];
  return {
    group,
    label: definition.label,
    roll,
    values: Object.fromEntries(
      definition.columns.map((column) => [column, row[column]]),
    ),
  };
}

export function rollPet(random = Math.random) {
  return Object.keys(UVG_PET_ROLL_GROUPS).reduce((results, group) => {
    const roll = Math.floor(random() * 50) + 1;
    results[group] = petResultFor(group, roll);
    return results;
  }, {});
}
